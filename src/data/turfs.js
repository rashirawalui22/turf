export function getTurfById(id) {
  return turfs.find((t) => t.id === id);
}

export function getSimilarTurfs(turf, limit = 3) {
  return turfs
    .filter((t) => t.id !== turf.id && (t.sport === turf.sport || t.area === turf.area))
    .slice(0, limit);
}
